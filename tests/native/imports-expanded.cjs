const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
module.exports = async ({page,invoke,button,output}) => {
  const cards = await invoke("save_card", {input:{id:null,name:"Cartão importação",institution:"Banco sintético",lastFour:null,brand:null,creditLimit:100000,closingDay:20,dueDay:28,defaultAccountId:null}});
  const cardId = cards.find(c=>c.name==="Cartão importação").id;
  const before = await invoke("get_balances");
  const csv = path.join(output,"card-import.csv");
  const content = "Data;Descrição;Valor;Parcelas;Fatura;Cartão;Loja;Modalidade;Intermediador\n21/09/2026;Compra importada;-10,01;3;2026-10;Cartão importação;Loja importada;online;Entrega importada";
  fs.writeFileSync(csv,content);
  const options = {delimiter:";",decimal:",",dateFormat:"dd/MM/yyyy",dateColumn:0,descriptionColumn:1,amountColumn:2,typeColumn:null,metadataColumns:{installments:3,invoice:4,card:5,merchant:6,channel:7,intermediary:8}};
  await assert.rejects(invoke("prepare_import",{content,format:"csv",options,accountId:1}));
  const first = await invoke("prepare_card_import",{content,format:"csv",options,cardId});
  assert.ok(first.rows[0].error);
  assert.equal((await invoke("query_purchases",{cardId,page:0})).total,0);
  await button("Importar").click(); await button("Compras no cartão").click();
  await page.getByLabel("Cartão do arquivo").selectOption(String(cardId));
  await page.getByLabel("Arquivo",{exact:true}).setInputFiles(csv);
  await button("Ler colunas").click();
  for(const [label,column] of [["quantidade total de parcelas",3],["primeira fatura (aaaa-mm)",4],["cartão",5],["estabelecimento",6],["modalidade",7],["intermediador",8]]) await page.getByLabel(`Coluna de ${label}`,{exact:true}).selectOption(String(column));
  await button("Pré-visualizar compras").click();
  await page.getByRole("cell",{name:/Compra importada/}).waitFor();
  assert.equal(await page.getByLabel("Importar compra 2").isDisabled(),true);
  await button("Revisar compra 2").click();
  await button("Salvar compra").click();
  await page.getByText("Confirme os dados da compra original.",{exact:true}).waitFor();
  await page.getByLabel(/Conferi a origem:/).check();
  await button("Salvar compra").click();
  await page.getByLabel("Importar compra 2").check();
  await button("Revisar confirmação de compras").click();
  assert.equal((await invoke("query_purchases",{cardId,page:0})).total,0);
  await button("Confirmar e importar compras").click();
  await page.getByText(/1 compras importadas/).waitFor();
  const saved = (await invoke("query_purchases",{cardId,page:0})).items[0];
  assert.equal(saved.amount,1001); assert.equal(saved.installmentCount,3); assert.equal(saved.merchant,"Loja importada");
  assert.deepEqual(await invoke("get_balances"),before);
  const duplicate = await invoke("prepare_card_import",{content,format:"csv",options,cardId});
  assert.equal(duplicate.rows[0].duplicate,true);
  const ofx = "<OFX><CCSTMTRS><CURDEF>BRL<CCACCTFROM><ACCTID>synthetic</CCACCTFROM><BANKTRANLIST><STMTTRN><TRNTYPE>DEBIT<DTPOSTED>20260921<TRNAMT>-12.34<FITID>card-native-1<NAME>OFX compra</STMTTRN></BANKTRANLIST></CCSTMTRS></OFX>";
  const parsed = await invoke("prepare_card_import",{content:ofx,format:"ofx",options:null,cardId});
  await assert.rejects(invoke("prepare_import",{content:ofx.replace("<CCSTMTRS>","< ccstmtrs >"),format:"ofx",options:null,accountId:1}));
  assert.ok(parsed.rows[0].error); assert.equal(parsed.rows[0].row.purchase.installmentCount,0);
  const row=parsed.rows[0].row; row.purchase.installmentCount=1; row.confirmedPurchase=true;
  const args={requestId:"native-card-ofx-confirmation",rows:[row],currency:"BRL",allowDuplicates:false};
  assert.equal((await invoke("commit_card_import",args)).imported,1);
  assert.equal((await invoke("commit_card_import",args)).repeated,true);
  await assert.rejects(invoke("commit_card_import",{...args,requestId:"native-card-ofx-duplicate",allowDuplicates:true}));
  await button("Pré-visualizar compras").click();
  await button("Revisar compra 2").click(); await page.getByLabel(/Conferi a origem:/).check(); await button("Salvar compra").click();
  await page.getByLabel("Importar compra 2").check(); await button("Revisar confirmação de compras").click();
  assert.equal(await button("Confirmar e importar compras").isDisabled(),true);
  await button("Fechar").click();
  for(const theme of ["light","dark","system"]) {
    await require("./theme.cjs")(page,theme);
    await page.evaluate(fs.readFileSync(require.resolve("axe-core/axe.min.js"),"utf8"));
    assert.deepEqual(await page.evaluate(async()=> (await axe.run(document,{runOnly:{type:"tag",values:["wcag2a","wcag2aa","wcag21aa"]}})).violations),[]);
  }
  await page.setViewportSize({width:600,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(output,"card-import-narrow.png"),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  fs.writeFileSync(path.join(output,"expanded-import.json"),JSON.stringify({saved,cardId,readonly:true,idempotent:true,duplicates:true,axe:true},null,2));
  return {cardId,saved};
};
